# 1. Crear proyecto con Vite (plantilla oficial React + SWC)
pnpm create vite@latest front -- --template react-swc

# 2. Entrar al proyecto
cd front

# 3. Instalar dependencias principales (React 19)
pnpm add react@latest react-dom@latest

# 4. Instalar librerías adicionales
pnpm add react-bootstrap bootstrap react-router-dom@latest react-redux @reduxjs/toolkit react-hook-form date-fns
